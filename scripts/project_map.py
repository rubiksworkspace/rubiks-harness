#!/usr/bin/env python3
"""Generate .rubiks/map.md: one table row per source file, for developers and agents.

Everything comes from git and the source text, with no LLM and no index to keep
running. Each file is one line, so the table can be searched with grep or read in
an editor. Rerun after changes; the header records the commit it describes.

Usage: project_map.py [repo] [--check]
  --check exits 1 if the map is missing or describes a different commit.
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

LANGUAGES = {
    ".rs": "Rust", ".py": "Python", ".ts": "TypeScript", ".tsx": "TypeScript",
    ".js": "JavaScript", ".jsx": "JavaScript", ".go": "Go", ".c": "C", ".h": "C",
    ".cc": "C++", ".cpp": "C++", ".java": "Java", ".kt": "Kotlin", ".swift": "Swift",
    ".rb": "Ruby", ".sh": "Shell", ".md": "Markdown", ".toml": "TOML",
    ".yml": "YAML", ".yaml": "YAML", ".sql": "SQL",
}
SKIPPED_DIRS = {"vendor", "third_party", "node_modules", "target", "dist", "build", ".rubiks"}
SYMBOLS = {
    "Rust": r"^pub(?:\([a-z]+\))? (?:async )?(?:unsafe )?(?:fn|struct|enum|trait|type|mod|const|static) ([A-Za-z_]\w*)",
    "Python": r"^(?:async )?(?:def|class) ([A-Za-z_]\w*)",
    "TypeScript": r"^export (?:default )?(?:async )?(?:function|class|interface|type|const|enum) ([A-Za-z_]\w*)",
    "JavaScript": r"^export (?:default )?(?:async )?(?:function|class|const) ([A-Za-z_]\w*)",
    "Go": r"^(?:func|type) (?:\([^)]*\) )?([A-Z]\w*)",
    "Markdown": r"^##? (.+)$",
}
TEST_PATH = re.compile(r"(^|/)(tests?|__tests__)(/|$)|(_test|_tests|\.test|\.spec)\.[a-z]+$|(^|/)test_[^/]+$")
TEST_CODE = re.compile(r"#\[cfg\(test\)\]|#\[test\]|#\[gpui::test")
MAX_SYMBOLS = 6
MAX_PURPOSE = 90


def git(repo, *args):
    return subprocess.run(
        ["git", "-C", str(repo), *args], check=True, capture_output=True, text=True, errors="replace"
    ).stdout


def last_changes(repo):
    """Newest commit per path, from one pass over history."""
    changes, current = {}, ""
    for line in git(repo, "log", "--format=@%h %ad", "--date=short", "--name-only").splitlines():
        if line.startswith("@"):
            current = line[1:]
        elif line:
            changes.setdefault(line, current)
    return changes


def purpose(language, text):
    """The file's own first line of description; never written by a model."""
    patterns = {
        "Rust": r"^\s*//!\s*(\S.*)$",
        "Python": r'^\s*(?:"""|\'\'\')\s*(\S.*?)(?:"""|\'\'\')?\s*$',
        "Markdown": r"^#\s+(.+)$",
    }
    found = re.search(patterns.get(language, r"^\s*(?://|#)\s+(\S.*)$"), text[:4000], re.M)
    return found.group(1).strip()[:MAX_PURPOSE] if found else ""


def cell(value):
    return value.replace("|", "\\|").replace("\n", " ")


def area_of(path):
    """The crate for paths under crates/, otherwise the top-level directory."""
    parts = path.split("/")
    if parts[0] == "crates" and len(parts) > 2:
        return "/".join(parts[:2])
    return parts[0] if len(parts) > 1 else "(root)"


def symbols(language, text):
    return re.findall(SYMBOLS[language], text, re.M) if language in SYMBOLS else []


def row(path, repo, changes):
    source = repo / path
    language = LANGUAGES[source.suffix.lower()]
    text = source.read_text(errors="replace")
    area = area_of(path)
    names = symbols(language, text)
    shown = ", ".join(names[:MAX_SYMBOLS]) + (f" +{len(names) - MAX_SYMBOLS}" if len(names) > MAX_SYMBOLS else "")
    tests = "test file" if TEST_PATH.search(path) else "inline" if TEST_CODE.search(text) else ""
    return (
        f"| {cell(path)} | {cell(area)} | {language} | {text.count(chr(10)) + 1} "
        f"| {cell(purpose(language, text))} | {cell(shown)} | {tests} | {changes.get(path, '')} |"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("repo", nargs="?", default=".")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    repo = Path(git(args.repo, "rev-parse", "--show-toplevel").strip())
    head = git(repo, "rev-parse", "--short", "HEAD").strip()
    target = repo / ".rubiks" / "map.md"
    stamp = f"Describes commit `{head}`."

    if args.check:
        current = target.exists() and stamp in target.read_text(errors="replace")[:600]
        print("map is current" if current else f"map is stale or missing: {target}")
        sys.exit(0 if current else 1)

    paths = [
        path for path in git(repo, "ls-files").splitlines()
        if Path(path).suffix.lower() in LANGUAGES
        and not SKIPPED_DIRS.intersection(path.split("/")[:-1])
        and (repo / path).is_file()
    ]
    changes = last_changes(repo)
    lines = [
        "# Project map",
        "",
        f"Generated by `project_map.py` from git and source text. {stamp} Don't edit by hand. {len(paths)} files.",
        "",
        "| Path | Area | Language | Lines | Purpose | Main symbols | Tests | Last change |",
        "|---|---|---|---|---|---|---|---|",
        *(row(path, repo, changes) for path in sorted(paths)),
    ]
    target.parent.mkdir(exist_ok=True)
    # Generated files stay out of git; the checks file is a team decision and is shared.
    ignore = target.parent / ".gitignore"
    if not ignore.exists():
        ignore.write_text("*\n!.gitignore\n!checks.toml\n")
    target.write_text("\n".join(lines) + "\n")
    print(f"{target}: {len(paths)} files, {target.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
